#!/usr/bin/env python3
"""The macOS build's guest-to-host calls (port/macos/README.md).

The game runs as WebAssembly translated to C (wasm2c), so every function the
guest calls and does not define is an import of module "env", which wasm2c
declares as w2c_env_<name>(struct w2c_env *, ...) with WebAssembly's types:
i32 for int, unsigned, pointers and the like, i64 for 64-bit integers, f32
and f64. This script reads the C prototypes of those functions, as the guest
sees them (port/macos/host_imports.h and port/linux/src/posix.h), and writes
the host's side: for each, a w2c_env_<name> that turns the guest's pointers
(offsets into its memory) into host pointers and calls the host function of
the same name with the host prefix (host_<name>, or posix_<name> as it is).

Pointers are recognised by their '*'. A pointer the host returns must point
into guest memory; the prototypes here return none (handles are integers).

Usage: macos_imports.py output.c header...
"""

import re
import sys
from typing import List, Tuple

# C types the guest passes, by their WebAssembly type
I64_TYPES = {"long long", "unsigned long long", "int64_t", "uint64_t", "Uint64", "Sint64", "SDL_WindowFlags"}
F32_TYPES = {"float"}
F64_TYPES = {"double"}


def wasm_type(c_type: str) -> str:
    c_type = " ".join(c_type.replace("const ", "").split())
    if "*" in c_type:
        return "u32"
    if c_type in I64_TYPES:
        return "u64"
    if c_type in F32_TYPES:
        return "f32"
    if c_type in F64_TYPES:
        return "f64"
    return "u32"


def parse(path: str) -> List[Tuple[str, str, List[Tuple[str, str]]]]:
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"^\s*#[^\n]*", "", text, flags=re.M)
    functions = []
    for match in re.finditer(r"([A-Za-z_][\w \*]*?)\b((?:host|posix)_\w+)\s*\(([^;{]*?)\)\s*(?:__attribute__\(\(.*?\)\)\s*)?;",
                             text, re.S):
        result, name, params = match.groups()
        result = " ".join(result.split())
        if result.startswith("typedef") or result.startswith("extern \"C\""):
            continue
        params = " ".join(params.split())
        args: List[Tuple[str, str]] = []
        if params and params != "void":
            for index, param in enumerate(params.split(",")):
                param = param.strip()
                m = re.match(r"(.*?)(\w+)\s*$", param)
                c_type = m.group(1).strip() if m and m.group(1).strip() else param
                args.append((c_type, f"a{index}"))
        functions.append((result, name, args))
    return functions


def main() -> None:
    output, headers = sys.argv[1], sys.argv[2:]
    functions = []
    for header in headers:
        functions += parse(header)
    out = [
        "/* generated by tools/macos_imports.py; do not edit */",
        "#include \"host.h\"",
        "#include \"halo_w2c.h\"",
        "",
    ]
    for result, name, args in functions:
        host_args = ", ".join(f"{c} {n}" for c, n in args) or "void"
        out.append(f"{result} {name}({host_args});")
    out.append("")
    for result, name, args in functions:
        wasm_args = "".join(f", {wasm_type(c)} {n}" for c, n in args)
        call_args = []
        for c, n in args:
            if "*" in c:
                call_args.append(f"({c})HOST_POINTER({n})")
            else:
                call_args.append(f"({c}){n}")
        call = f"{name}({', '.join(call_args)})"
        returned = wasm_type(result) if result != "void" else "void"
        out.append(f"{returned} w2c_env_{name}(struct w2c_env *instance{wasm_args})")
        out.append("{")
        out.append("\t(void)instance;")
        if result == "void":
            out.append(f"\t{call};")
        elif "*" in result:
            out.append(f"\treturn HOST_OFFSET({call});")
        else:
            out.append(f"\treturn ({returned}){call};")
        out.append("}")
        out.append("")
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
