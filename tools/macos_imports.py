#!/usr/bin/env python3
"""The macOS build's guest-to-host calls (port/macos/README.md).

The game runs as WebAssembly translated to C (wasm2c), so every function the
guest calls and does not define is an import of module "env", which wasm2c
declares as w2c_env_<name>(struct w2c_env *, ...) with WebAssembly's types:
i32 for int, unsigned, pointers and the like, i64 for 64-bit integers, f32
and f64. This script reads the C prototypes of those functions as the guest
sees them and writes the host's side, a w2c_env_<name> for each that turns
the guest's pointers (offsets into its memory) into host pointers and calls
the host function:

- port/macos/guest/guest_host.h's host_<name>: the host's host_<name>
  (port/macos/host), declared here with the guest's types but for a pointer
  to pointers (a list of strings), which the host gets as the list of guest
  offsets it is, const uint32_t *;
- port/linux/src/posix.h's posix_<name>, which the guest calls through
  hostposix_<name> (tools/android_posix_stubs.py's wrappers, which copy errno
  back): posix_*.c's own, compiled into the host. The directory handle of
  posix_directory_* is a number, not a pointer.

Usage: macos_imports.py output.c guest_host.h posix.h
"""

import re
import sys
from typing import List, Tuple

# C types the guest passes, by their WebAssembly type
I64_TYPES = {"long long", "unsigned long long", "int64_t", "uint64_t", "Uint64", "Sint64"}
F32_TYPES = {"float"}
F64_TYPES = {"double"}

# (function, argument index) whose void * is a handle, not guest memory; and
# the functions that return one
HANDLE_ARGUMENTS = {("posix_directory_next", 0), ("posix_directory_close", 0)}
HANDLE_RESULTS = {"posix_directory_open"}
# defined by the host itself (port/macos/host/host_main.c)
MANUAL = {"host_errno"}


def wasm_type(c_type: str) -> str:
    c_type = " ".join(c_type.replace("const ", "").split())
    if "*" in c_type:
        return "u32"
    if c_type in I64_TYPES:
        return "u64"
    if c_type in F32_TYPES:
        return "f32"
    if c_type in F64_TYPES:
        return "f64"
    return "u32"


def is_pointer_list(c_type: str) -> bool:
    return c_type.count("*") >= 2


def parse(path: str, prefix: str) -> List[Tuple[str, str, List[str]]]:
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"^\s*#[^\n]*", "", text, flags=re.M)
    functions = []
    for match in re.finditer(rf"([A-Za-z_][\w \*]*?)\b({prefix}_\w+)\s*\(([^;{{]*?)\)\s*;", text, re.S):
        result, name, params = match.groups()
        result = " ".join(result.split())
        if result.startswith("typedef") or name in MANUAL:
            continue
        params = " ".join(params.split())
        types: List[str] = []
        if params and params != "void":
            for param in params.split(","):
                param = param.strip()
                m = re.match(r"(.*?[\s\*])(\w+)$", param)
                types.append(m.group(1).strip() if m else param)
        functions.append((result, name, types))
    return functions


def main() -> None:
    output, guest_host, posix = sys.argv[1:4]
    out = [
        "/* generated by tools/macos_imports.py; do not edit */",
        "#include \"host.h\"",
        "#include \"halo_w2c.h\"",
        "#include \"posix.h\"",
        "",
    ]
    host_functions = parse(guest_host, "host")
    for result, name, types in host_functions:
        host_types = ["const uint32_t *" if is_pointer_list(t) else t for t in types]
        params = ", ".join(f"{t} a{i}" for i, t in enumerate(host_types)) or "void"
        out.append(f"{result} {name}({params});")
    out.append("")

    def wrapper(import_name: str, result: str, name: str, types: List[str], posix_call: bool) -> None:
        wasm_args = "".join(f", {wasm_type(t)} a{i}" for i, t in enumerate(types))
        call_args = []
        for index, c_type in enumerate(types):
            if (name, index) in HANDLE_ARGUMENTS:
                call_args.append(f"({c_type})(uintptr_t)a{index}")
            elif is_pointer_list(c_type):
                call_args.append(f"(const uint32_t *)HOST_POINTER(a{index})")
            elif "*" in c_type:
                call_args.append(f"({c_type})HOST_POINTER(a{index})")
            else:
                call_args.append(f"({c_type})a{index}")
        call = f"{name}({', '.join(call_args)})"
        returned = wasm_type(result) if result != "void" else "void"
        out.append(f"{returned} w2c_env_{import_name}(struct w2c_env *instance{wasm_args})")
        out.append("{")
        out.append("\t(void)instance;")
        if result == "void":
            out.append(f"\t{call};")
            if posix_call:
                out.append("\thost_errno_set_from_host();")
        else:
            if name in HANDLE_RESULTS:
                value = f"(u32)(uintptr_t){call}"
            elif "*" in result:
                value = f"HOST_OFFSET({call})"
            else:
                value = f"({returned}){call}"
            out.append(f"\t{returned} result = {value};")
            if posix_call:
                out.append("\thost_errno_set_from_host();")
            out.append("\treturn result;")
        out.append("}")
        out.append("")

    for result, name, types in host_functions:
        wrapper(name, result, name, types, False)
    for result, name, types in parse(posix, "posix"):
        wrapper("hostposix_" + name[len("posix_"):], result, name, types, True)
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
